import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const url = process.env.PAPER_TEST_URL
if (!url) throw new Error('Set PAPER_TEST_URL')
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 960 } })
  page.on('pageerror', error => errors.push(String(error)))
  await page.goto(url, { waitUntil: 'networkidle' })
  const go = async number => {
    await page.locator('.pr-page-input input').fill(String(number))
    await page.locator('.pr-page-input input').press('Enter')
    await page.locator(`[data-pdf-page="${number}"][data-render-status="ready"]`).waitFor({ timeout: 20000 })
  }
  await page.locator('[data-pdf-page="1"][data-render-status="ready"]').waitFor({ timeout: 20000 })
  const title = page.locator('[data-pdf-page="1"] .pr-text-layer span').filter({ hasText: 'SuperMimic:' }).first()
  await page.evaluate(() => {
    window.testHarness.setDraft('我的未完成草稿，不应被自动发送。')
    const [draft] = window.testHarness.conversation.createDrafts('test-session', [new File(['personal draft'], '未发送附件.txt', { type: 'text/plain' })])
    window.testHarness.actions.addAttachments([draft.id])
  })
  const untouchedDraft = await page.evaluate(() => window.testHarness.getDraft())
  const untouchedIds = await page.evaluate(() => [...window.testHarness.attachments])
  await title.evaluate(node => {
    const range = document.createRange(); range.setStart(node.firstChild, 0); range.setEnd(node.firstChild, 10)
    const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  await page.getByRole('toolbar', { name: '选中文字的操作' }).getByRole('button', { name: '解释', exact: true }).click()
  await page.waitForFunction(() => window.testHarness.sentMessages.length === 1)
  assert.match(await page.evaluate(() => window.testHarness.sentMessages[0].text), /来源：SuperMimic.pdf，第 1 页/)
  assert.doesNotMatch(await page.evaluate(() => window.testHarness.sentMessages[0].text), /未完成草稿/)
  assert.equal(await page.evaluate(() => window.testHarness.getDraft()), untouchedDraft)
  assert.deepEqual(await page.evaluate(() => [...window.testHarness.attachments]), untouchedIds)
  assert.equal(await page.evaluate(() => window.testHarness.sentMessages[0].files.length), 0)

  await page.evaluate(() => getSelection()?.removeAllRanges())
  await go(2)
  const paragraph = page.locator('[data-pdf-page="2"] .pr-text-layer span').filter({ hasText: 'SuperMimic addresses this inefficiency' }).first()
  const hover = async () => {
    await paragraph.hover()
    await page.getByRole('toolbar', { name: '悬停段落的操作' }).waitFor()
  }
  await hover()
  await page.getByRole('toolbar', { name: '悬停段落的操作' }).getByRole('button', { name: '翻译', exact: true }).click()
  await page.waitForFunction(() => window.testHarness.sentMessages.length === 2)
  const translation = await page.evaluate(() => window.testHarness.sentMessages[1])
  assert.match(translation.text, /翻译/)
  assert.match(translation.text, /第 2 页/)
  assert.match(translation.text, /logged simulator transitions/)
  assert.match(translation.text, /non-differentiable implementations/)
  assert.equal(translation.sessionId, 'test-session')
  assert.equal(translation.mode, 'queue')
  assert.equal(await page.evaluate(() => window.testHarness.getDraft()), untouchedDraft)
  assert.equal(await page.evaluate(() => window.testHarness.references.length), 0)

  await hover()
  await page.getByRole('toolbar', { name: '悬停段落的操作' }).getByRole('button', { name: '提问', exact: true }).click()
  await page.waitForFunction(() => window.testHarness.references.length === 1)
  assert.equal(await page.evaluate(() => window.testHarness.sentMessages.length), 2, 'ask still waits for the user to complete the question')
  assert.ok((await page.evaluate(() => window.testHarness.getDraft())).startsWith(untouchedDraft))
  const draftAfterAsk = await page.evaluate(() => window.testHarness.getDraft())

  await go(7)
  const chartTitle = page.locator('[data-pdf-page="7"] .pr-text-layer span').filter({ hasText: 'Normalized return' }).first()
  const box = await chartTitle.boundingBox()
  await page.mouse.move(box.x + 35, box.y + 45)
  await page.getByRole('toolbar', { name: '图表操作' }).getByRole('button', { name: '解释', exact: true }).click()
  await page.waitForFunction(() => window.testHarness.sentMessages.length === 3)
  assert.equal(await page.evaluate(() => window.testHarness.sentMessages[2].text), '解释这张图表')
  assert.equal(await page.evaluate(() => window.testHarness.sentMessages[2].files[0].type), 'image/png')
  assert.ok(await page.evaluate(() => window.testHarness.sentMessages[2].files[0].size > 1000))
  assert.match(await page.evaluate(() => window.testHarness.sentMessages[2].files[0].name), /第7页图表.png/)
  assert.equal(await page.evaluate(() => window.testHarness.getDraft()), draftAfterAsk)
  assert.deepEqual(await page.evaluate(() => [...window.testHarness.attachments]), untouchedIds)

  await go(2)
  await page.evaluate(() => { window.testHarness.conversation.failNextSend = 1 })
  await hover()
  await page.getByRole('toolbar', { name: '悬停段落的操作' }).getByRole('button', { name: '解释', exact: true }).click()
  await page.getByRole('button', { name: '重试发送', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.testHarness.sentMessages.length), 3)
  assert.equal(await page.evaluate(() => window.testHarness.getDraft()), draftAfterAsk)
  await page.getByRole('button', { name: '重试发送', exact: true }).click()
  await page.waitForFunction(() => window.testHarness.sentMessages.length === 4)
  assert.equal(await page.locator('.pr-notice').count(), 0)

  const attempts = await page.evaluate(() => window.testHarness.conversation.sendAttempts)
  await page.evaluate(() => { window.testHarness.conversation.sendDelay = 1000 })
  await hover()
  await page.getByRole('toolbar', { name: '悬停段落的操作' }).getByRole('button', { name: '解释', exact: true }).click()
  await hover()
  await page.getByRole('toolbar', { name: '悬停段落的操作' }).getByRole('button', { name: '解释', exact: true }).click()
  await page.waitForFunction(() => window.testHarness.sentMessages.length === 5)
  assert.equal(await page.evaluate(() => window.testHarness.conversation.sendAttempts), attempts + 1, 'repeated pending clicks send only once')

  await hover()
  await page.getByRole('toolbar', { name: '悬停段落的操作' }).getByRole('button', { name: '翻译', exact: true }).click()
  await page.evaluate(() => window.testHarness.renderLocal())
  await page.locator('input[type=file]').waitFor()
  await page.waitForTimeout(1100)
  assert.equal(await page.evaluate(() => window.testHarness.sentMessages.length), 5, 'navigation cancels an unaccepted send from the outgoing reader')
  assert.equal(await page.evaluate(() => window.testHarness.getDraft()), draftAfterAsk)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ status: 'passed', shortExplain: true, fullPassageTranslate: true, imageExplain: true, preservesComposerAndAttachments: true, askStaysDraft: true, explicitRetry: true, deduplicated: true, navigationCancellation: true, errors }))
} finally { await browser.close() }
